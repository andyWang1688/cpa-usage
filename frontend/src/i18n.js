export function translate(dictMap, lang, key, params = {}) {
  const dict = dictMap[lang] || dictMap.zh || {};
  const parts = key.split(".");
  let cur = dict;
  for (const part of parts) {
    if (cur == null || typeof cur !== "object") {
      cur = undefined;
      break;
    }
    cur = cur[part];
  }
  if (typeof cur !== "string") {
    // fallback to zh
    let fb = dictMap.zh || {};
    for (const part of parts) {
      if (fb == null || typeof fb !== "object") {
        fb = undefined;
        break;
      }
      fb = fb[part];
    }
    cur = typeof fb === "string" ? fb : key;
  }
  return cur.replace(/\{\{(\w+)\}\}/g, (_, k) => (params[k] != null ? params[k] : `{{${k}}}`));
}

export function getTranslator(lang, dictMap = translations) {
  return (key, params) => translate(dictMap, lang, key, params);
}

export function readLang(storage, navLang) {
  try {
    const saved = (storage ?? (typeof localStorage !== "undefined" ? localStorage : null))?.getItem(LANG_STORAGE_KEY);
    if (saved === "zh" || saved === "en") return saved;
  } catch {}
  try {
    const envLang = navLang !== undefined ? navLang : (typeof navigator !== "undefined" ? navigator.language : null);
    if (envLang && typeof envLang === "string") {
      return envLang.toLowerCase().startsWith("zh") ? "zh" : "en";
    }
  } catch {}
  return "zh";
}

export function saveLang(lang, storage) {
  try {
    (storage ?? (typeof localStorage !== "undefined" ? localStorage : null))?.setItem(LANG_STORAGE_KEY, lang);
  } catch {}
}
