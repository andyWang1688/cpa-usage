export function translate(lang, key, params = {}) {
  const messages = (LANGUAGES[lang] ?? LANGUAGES[DEFAULT_LANGUAGE]).messages;
  let message = messages[key] ?? zh[key] ?? key;
  if (typeof message === "object") {
    message = params.count === 0 && message.zero
      ? message.zero
      : message[new Intl.PluralRules(lang).select(params.count ?? 0)] ?? message.other;
  }
  return message.replace(/\{(\w+)\}/g, (match, name) => {
    if (!(name in params)) return match;
    const value = params[name];
    return typeof value === "number" ? value.toLocaleString(lang) : String(value);
  });
}

export function translateServerMessage(lang, message) {
  const known = serverMessages[lang];
  if (!known || !message) return message;
  if (known[message]) return known[message];
  const http = /^价格源返回 HTTP (\d+)$/.exec(message);
  return http ? translate(lang, "priceSourceHTTP", { status: http[1] }) : message;
}

export function detectLanguage(storage, preferred) {
  try {
    const saved = (storage ?? localStorage).getItem(LANGUAGE_STORAGE_KEY);
    if (LANGUAGES[saved]) return saved;
  } catch {}
  const languages = preferred ?? (typeof navigator === "undefined" ? [] : navigator.languages ?? [navigator.language]);
  return languages.some((l) => /^pt(-|$)/i.test(l ?? "")) ? "pt-BR" : DEFAULT_LANGUAGE;
}

export function saveLanguage(lang, storage) {
  try { (storage ?? localStorage).setItem(LANGUAGE_STORAGE_KEY, lang); } catch {}
}

// Binds translation and locale-aware formatting to one language.
export function createI18n(requested) {
  const lang = LANGUAGES[requested] ? requested : DEFAULT_LANGUAGE;
  const config = LANGUAGES[lang];
  const t = (key, params) => translate(lang, key, params);
  const moneyOptions = { locale: config.moneyLocale, display: config.moneyDisplay };
  const number = (n, options) => Number(n).toLocaleString(config.numberLocale, options);
  return {
    lang,
    t,
    dateLocale: config.dateLocale,
    formats: config.formats,
    localCurrency: config.localCurrency,
    bucketTick: config.bucketTick,
    fmt: (n) => fmt(n, config.numberLocale),
    compact: (n) => compact(n, config.compactLocale),
    number,
    percent: (n) => `${number(n, { minimumFractionDigits: 1, maximumFractionDigits: 1 })}%`,
    dateTime: (date) => date.toLocaleString(config.numberLocale),
    withSymbol: (currency, amount) => `${currencySymbol(currency, moneyOptions)}${config.symbolGap}${amount}`,
    money: (n, currency, fxRate, maximumFractionDigits) =>
      money(n, currency, fxRate, maximumFractionDigits, { ...moneyOptions, unpriced: t("unpriced") }),
    keyLabel: (key) => (key === UNKNOWN_KEY ? t("unknownKey") : key),
    serverMessage: (message) => translateServerMessage(lang, message),
    // Request errors carry a message key in `code`; others come from the server.
    errorText: (error) => (error?.code ? t(error.code, error.params) : translateServerMessage(lang, error?.message ?? String(error))),
  };
}
